// FP-trap suite: every verified-safe fragment must produce ZERO T1/T2 findings
// across ALL rules. CI-enforced like the corpus replay. Runs offline.
import { runScan, ScanInput } from '../../src/engine';
import { TRAPS } from './traps';

function allChanged(text: string): ScanInput {
  const n = text.split('\n').length;
  const c = new Set<number>();
  for (let i = 1; i <= n; i++) c.add(i);
  return {
    files: [{ diff: { newPath: 'x.rs', oldPath: 'x.rs', status: 'modified', changedLines: c, removedLines: new Set(), hunks: [], binary: false }, headText: text, baseText: null }],
    context: { source: 'patch' },
  };
}

async function main() {
  let fail = 0;
  const rows: string[] = [
    '# FP-trap suite (bench/fp-traps)',
    '',
    'Auto-generated by `npm run fp-traps`. Each fragment is a verified-safe pattern',
    'that tempts a detector; it MUST produce zero Tier-1/Tier-2 findings.',
    '',
    '| trap | tempts | repo | T1/T2 findings | verdict |',
    '| --- | --- | --- | --- | --- |',
  ];
  for (const t of TRAPS) {
    const r = await runScan(allChanged(t.code), { includeTests: true });
    const t1t2 = r.findings.filter((f) => f.tier <= 2);
    const ok = t1t2.length === 0;
    if (!ok) fail++;
    const detail = ok ? '0' : t1t2.map((f) => `${f.ruleId}@L${f.line}`).join('; ');
    console.log(`${ok ? 'ok  ' : 'XX  '} ${t.id} (${t.tempts})  ${ok ? 'clean' : 'FIRED: ' + detail}`);
    rows.push(`| ${t.id} | \`${t.tempts}\` | ${t.repo} | ${detail} | ${ok ? '✅' : '❌'} |`);
  }
  rows.push('', `**${TRAPS.length - fail}/${TRAPS.length} traps silent.**`, '');
  const path = require('path') as typeof import('path');
  const fs = require('fs') as typeof import('fs');
  fs.writeFileSync(path.join(__dirname, '..', '..', '..', 'bench', 'fp-traps', 'FP-TRAPS.md'), rows.join('\n'));
  console.log(`\n${TRAPS.length - fail}/${TRAPS.length} traps produce zero T1/T2 findings.`);
  if (fail) {
    console.error('FP-TRAP GATE FAILED');
    process.exit(1);
  }
  console.log('FP-TRAP GATE PASSED');
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
